def is_navigation_question(question: str) -> bool:
    """האם השאלה היא שאלת ניווט (ולא שאלה לימודית)."""
    text = question.strip().lower()
    return any(hint in text for hint in NAVIGATION_HINTS)


def find_destination(question: str) -> dict:
    """מחזיר את המסך שהכי מתאים לשאלה.

    התוצאה תמיד כוללת answer ו-link, ו-found אומר אם נמצא מסך מתאים.
    """
    text = question.strip().lower()
    for destination in DESTINATIONS:
        if any(keyword in text for keyword in destination["keywords"]):
            return {
                "found": True,
                "answer": destination["answer"],
                "link": destination["link"],
                "title": destination["title"],
            }
    return {
        "found": False,
        "answer": NOT_FOUND_ANSWER,
        "link": HOME_LINK,
        "title": "עמוד הבית",
    }
